#!/usr/bin/env python3
"""Generate repobeagle/rules/registry.py from the README rule table.

R4 keeps rule ids and their metadata explicit in code. The README table is the reviewed
source (what a rule means and which severities it can emit); this script turns it into
`Rule` objects so findings can carry a stable id instead of splitting titles, and so
`tests/test_registry.py` can fail when the table and the registry drift.

Usage: python3 tools/gen_rule_registry.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
TARGET = ROOT / "repobeagle" / "rules" / "registry.py"

HEADER = '''"""Rule registry: explicit rule ids and metadata (generated by tools/gen_rule_registry.py).

Do not edit by hand; edit the rule table in README.md and regenerate. Findings carry
`rule` derived from the finding title prefix, and consumers read that field instead of
splitting titles.
"""
from . import Rule

RULES: dict[str, Rule] = {
'''


def rows():
    out = []
    for line in README.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| `"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 3:
            continue
        ids = re.findall(r"`([^`]+)`", cells[0])
        meaning = cells[1]
        severity = cells[2]
        for rid in ids:
            if re.fullmatch(r"[a-z0-9][a-z0-9-]*", rid):
                out.append((rid, meaning, severity))
    return out


def render():
    lines = [HEADER]
    for rid, meaning, severity in rows():
        lines.append(f"    {rid!r}: Rule(id={rid!r}, severity={severity!r},\n"
                     f"                 meaning={meaning!r},\n"
                     f"                 docs='README.md#privacy-telemetry-and-trackers'),\n")
    lines.append("}\n")
    return "".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print("registry is stale: run python3 tools/gen_rule_registry.py", file=sys.stderr)
            return 1
        print(f"registry matches the README rule table ({len(rows())} rules)")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(rows())} rules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
